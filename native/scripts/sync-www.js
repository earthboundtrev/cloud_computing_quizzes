#!/usr/bin/env node
/**
 * Copy runtime web assets from repo root into native/www (gitignored).
 * Aligns with sw.js PRECACHE_PATHS plus manifest and favicon.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const NATIVE_ROOT = path.join(__dirname, '..');
const REPO_ROOT = path.join(NATIVE_ROOT, '..');
const WWW = path.join(NATIVE_ROOT, 'www');

function readPrecachePaths() {
  const sw = fs.readFileSync(path.join(REPO_ROOT, 'sw.js'), 'utf8');
  const m = sw.match(/const PRECACHE_PATHS = \[([\s\S]*?)\];/);
  if (!m) throw new Error('PRECACHE_PATHS not found in sw.js');
  return m[1]
    .split('\n')
    .map(function (line) {
      const hit = line.trim().match(/^['"]([^'"]+)['"],?$/);
      return hit ? hit[1] : null;
    })
    .filter(Boolean);
}

function rimraf(dir) {
  if (!fs.existsSync(dir)) return;
  fs.readdirSync(dir).forEach(function (entry) {
    const p = path.join(dir, entry);
    if (fs.statSync(p).isDirectory()) rimraf(p);
    else fs.unlinkSync(p);
  });
  fs.rmdirSync(dir);
}

function copyFile(rel) {
  const src = path.join(REPO_ROOT, rel.replace(/^\//, ''));
  const dest = path.join(WWW, rel.replace(/^\//, ''));
  if (!fs.existsSync(src)) {
    console.warn('skip missing', rel);
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function syncBuildMeta() {
  const sw = fs.readFileSync(path.join(REPO_ROOT, 'sw.js'), 'utf8');
  const nameMatch = sw.match(/const CACHE_NAME = '([^']+)'/);
  const cacheName = nameMatch ? nameMatch[1] : 'web';
  const content =
    '/** Autogenerated by native/scripts/sync-www.js */\n' +
    "window.CLOUDCRAM_WEB_CACHE_NAME = '" +
    cacheName +
    "';\n";
  const dest = path.join(REPO_ROOT, 'build-meta.js');
  fs.writeFileSync(dest, content);
  copyFile('/build-meta.js');
}

function main() {
  if (fs.existsSync(WWW)) rimraf(WWW);
  fs.mkdirSync(WWW, { recursive: true });

  const paths = readPrecachePaths();
  paths.forEach(copyFile);

  ['manifest.json', 'favicon.ico'].forEach(function (extra) {
    if (paths.indexOf('/' + extra) < 0) copyFile('/' + extra);
  });

  syncBuildMeta();
  console.log('Synced', paths.length, 'paths to native/www');
}

main();